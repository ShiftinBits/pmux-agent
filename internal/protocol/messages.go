func (m *PingRequest) MessageType() string { return "ping" }

// CreateSessionRequest requests creation of a new tmux session.
type CreateSessionRequest struct {
	Type string `msgpack:"type"`
}

func (m *CreateSessionRequest) MessageType() string { return "create_session" }

// AuthResponseRequest proves the connecting peer possesses the pairing shared
// secret (AUTH V2). It is sent as the first DataChannel message in reply to an
// AuthChallengeEvent. The MAC covers the transcript
//
//	T = hostNonce(32) || mobileNonce(32) || hostCertFp(32) || mobileCertFp(32)
//
// where each certFp is the raw SHA-256 of that side's DER DTLS certificate, so
// the proof is bound to this DTLS session and cannot be relayed through a
// man-in-the-middle holding different certificates:
//
//	mac = base64std(HMAC-SHA256(sharedSecret, ASCII("pocketmux-auth-v2 mobile->host") || T))
//
// The host rejects the connection if the response is missing, malformed, or
// fails verification, then proves itself back with an AuthConfirmEvent. This
// authenticates both peers independently of the (untrusted) signaling server.
type AuthResponseRequest struct {
	Type  string `msgpack:"type"`
	Mac   string `msgpack:"mac"`   // base64std HMAC-SHA256 over the mobile->host label and T
	Nonce string `msgpack:"nonce"` // base64std of 32 random bytes generated by the mobile for this connection
}

func (m *AuthResponseRequest) MessageType() string { return "auth_response" }

// --- Host → Mobile (Events) ---

// SessionsEvent returns the full session tree.
// AgentVersion and UpdateAvailable are optional fields added for update
// notifications to the mobile app.
type SessionsEvent struct {
	Type            string        `msgpack:"type"`
	Sessions        []TmuxSession `msgpack:"sessions"`
	AgentVersion    string        `msgpack:"agentVersion,omitempty"`
	UpdateAvailable string        `msgpack:"updateAvailable,omitempty"` // latest version if update available, empty otherwise
}

func (m *SessionsEvent) MessageType() string { return "sessions" }

// OutputEvent sends terminal output data (raw bytes) from the attached pane.
