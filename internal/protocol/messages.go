// AuthChallengeEvent carries a per-connection random nonce the host sends as the
// first DataChannel message. The mobile must reply with an AuthResponseRequest
// whose MAC covers this nonce, the mobile's own nonce, and both DTLS
// certificate fingerprints (see AuthResponseRequest for the transcript T). The
// random nonce binds the proof to this connection, preventing replay of a
// captured response across sessions.
type AuthChallengeEvent struct {
	Type  string `msgpack:"type"`
	Nonce string `msgpack:"nonce"` // base64std of 32 random bytes generated by the host for this connection
	// V is the auth protocol version: 2 for the mutual DTLS-bound handshake.
	// pmux <=0.5.5 hosts omit it. Mirrors @pocketmux/shared's optional `v`.
	V int `msgpack:"v,omitempty"`
}

func (m *AuthChallengeEvent) MessageType() string { return "auth_challenge" }

// AuthConfirmEvent is the host's proof of the shared secret, sent after it has
// verified the mobile's AuthResponseRequest. It uses the same transcript T with
// a distinct direction label, so a mobile MAC can never be reflected back:
//
//	mac = base64std(HMAC-SHA256(sharedSecret, ASCII("pocketmux-auth-v2 host->mobile") || T))
//
// It is always the first message the host sends after the handshake; the mobile
// must verify it before trusting any further host messages.
type AuthConfirmEvent struct {
	Type string `msgpack:"type"`
	Mac  string `msgpack:"mac"` // base64std HMAC-SHA256 over the host->mobile label and T
}

func (m *AuthConfirmEvent) MessageType() string { return "auth_confirm" }

// --- tmux Data Types ---

// TmuxSession represents a tmux session with its window tree.
type TmuxSession struct {
	ID   string `msgpack:"id"`
	Name string `msgpack:"name"`
	// CreatedAt is a Unix timestamp in seconds.
	CreatedAt int64        `msgpack:"createdAt"`
	Windows   []TmuxWindow `msgpack:"windows"`
	// LastActivityAt is a Unix timestamp in seconds.
	LastActivityAt int64 `msgpack:"lastActivityAt"`
	Attached       bool  `msgpack:"attached"`
}

// TmuxWindow represents a window within a tmux session.
type TmuxWindow struct {
	ID     string     `msgpack:"id"`
	Name   string     `msgpack:"name"`
	Index  int        `msgpack:"index"`
	Active bool       `msgpack:"active"`
	Panes  []TmuxPane `msgpack:"panes"`
}

// TmuxPane represents a pane within a tmux window.
type TmuxPane struct {
	ID             string   `msgpack:"id"`
	Index          int      `msgpack:"index"`
	Active         bool     `msgpack:"active"`
	Size           PaneSize `msgpack:"size"`
	Title          string   `msgpack:"title"`
	CurrentCommand string   `msgpack:"currentCommand"`
}

// PaneSize holds terminal dimensions.
type PaneSize struct {
	Cols int `msgpack:"cols"`
	Rows int `msgpack:"rows"`
}
